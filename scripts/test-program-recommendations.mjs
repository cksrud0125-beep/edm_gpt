import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { stripTypeScriptTypes } from 'node:module';
const source = readFileSync('src/program-recommendations.ts','utf8').replace("import catalog from './data/programs.json';", `const catalog = ${readFileSync('src/data/programs.json','utf8')};`);
const js=stripTypeScriptTypes(source);
const {recommend,getQuestions}=await import('data:text/javascript;base64,'+Buffer.from(js).toString('base64'));
const a=(purpose,age,country,interest='일반 영어',schedule='내년 상반기 · 3개월')=>[purpose,age,country,schedule,'1,000만 원 이하',interest];
const adult=recommend(a('어학연수','30대 직장인','캐나다'));
assert(adult.some(x=>x.program.id==='thirty-plus-abroad'));
assert(recommend(a('어학연수','고등학생','캐나다')).every(x=>!x.program.id.includes('thirty-plus')));
assert(recommend(a('아직 잘 모르겠어요','성인','캐나다')).length===0);
assert(recommend(a('해외대학','고등학생','미국','학부')).every(x=>!(/석사|미대|어학연수/.test(x.program.title))));
assert(recommend(a('아트유학','대학생','영국','포트폴리오')).length>0);
assert(getQuestions(['아트유학'])[5].title.includes('전공'));
for(const x of adult) assert(!/미국|호주|영국/.test(x.program.title));
const catalog=JSON.parse(readFileSync('src/data/programs.json','utf8'));
assert.equal(new Set(catalog.programs.map(p=>p.url)).size,catalog.programs.length);
for(const p of catalog.programs) assert(p.url.startsWith('https://www.edmuhak.com/programs/'));
console.log('Passed: age exclusion, country matching, category separation, unknown intent, dynamic questions, official links and catalog deduplication.');
console.log('Example:',adult.map(x=>x.program.title));
const inputSource=stripTypeScriptTypes(readFileSync('src/advisor-input.ts','utf8'));
const {interpretMessage,nextQuestion}=await import('data:text/javascript;base64,'+Buffer.from(inputSource).toString('base64'));
const parsed=interpretMessage('32살 직장인이고 캐나다에서 3개월 어학연수를 원해요. 예산은 1,000만원이에요.',[]);
assert.deepEqual(parsed.answers.slice(0,5),['어학연수','32살','캐나다','3개월','1,000만원']);
assert(recommend(parsed.answers).some(x=>x.program.id==='thirty-plus-abroad'));
const revised=interpretMessage('캐나다 말고 영국으로 바꿔줘. 기간은 6개월이야.',parsed.answers);
assert.equal(revised.answers[2],'영국');
assert.equal(revised.answers[3],'6개월');
assert.equal(revised.answers[1],'32살');
assert(!recommend(revised.answers).some(x=>x.program.title.includes('캐나다')));
assert.equal(interpretMessage('대학생이고 캐나다 어학연수를 원해요',[]).answers[0],'어학연수');
assert.equal(interpretMessage('영국에서 디자인 석사를 하고 싶어요',[]).answers[0],'아트유학');
assert.equal(interpretMessage('토론토에서 세 달 영어 회화를 배우고 싶어요',[]).answers[3],'3개월');
assert.equal(nextQuestion(interpretMessage('캐나다에서 3개월 어학연수를 원해요',[]).answers),1);
assert.equal(interpretMessage('안녕하세요',[]).recognized,false);
assert.equal(interpretMessage('아직 모르겠어요',[],2).answers[2],'아직 미정');
console.log('Passed: multi-condition Korean input, corrections, previous-condition retention, aliases, unknown input and skipping known questions.');
const ukResults=recommend(['어학연수','30대 직장인','영국','3개월','','']);
assert(ukResults.length>3,'UK results must not be capped at three');
assert.equal(new Set(ukResults.map(x=>x.program.id)).size,ukResults.length);
assert.equal(ukResults.slice(0,3).length+ukResults.slice(3).length,ukResults.length);
console.log('Passed: uncapped, unique UK recommendations.');
const flowSource=stripTypeScriptTypes(readFileSync('src/advisor-flows.ts','utf8'));
const {flowQuestion,readyForResults}=await import('data:text/javascript;base64,'+Buffer.from(flowSource).toString('base64'));
const modes=['match','country','budget','school'];
for(const mode of modes)assert.equal(flowQuestion(mode,[],'',[]).field,0);
assert.equal(flowQuestion('budget',['어학연수'],'',[]).field,4);
assert.equal(flowQuestion('country',['어학연수'],'',[]).field,2);
assert.equal(flowQuestion('match',['해외대학','대학생'],'',[]).field,7);
assert.equal(flowQuestion('match',['아트유학','대학생','','','','','','패션','','','학부'],'',[]).field,11);
assert.equal(readyForResults('match',['어학연수','대학생','영국']),false);
const full=interpretMessage('대학생인데 내년 3월부터 캐나다로 6개월 어학연수 가고 싶어요. 예산은 1,500만원 정도예요.',[]).answers;
assert.equal(full[6],'내년 3월');assert.equal(full[3],'6개월');assert.equal(flowQuestion('match',full,'',[]).field,5);
assert.equal(interpretMessage('캐나다보다는 영국이 더 끌려',full).answers[2],'영국');
assert.equal(interpretMessage('예산 2천만원까지 가능해',full).answers[4],'2천만원');
assert.equal(interpretMessage('IELTS 6.5', ['해외대학'],9).answers[0],'해외대학');
assert.equal(interpretMessage('IELTS 6.5', ['해외대학'],9).answers[9],'IELTS 6.5');
console.log('Passed: category branches, quick modes, timing extraction, skipped known conditions and corrections.');
